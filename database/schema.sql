CREATE TABLE IF NOT EXISTS categorias (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(100) NOT NULL UNIQUE,ativo TINYINT(1) DEFAULT 1) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS marcas (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(100) NOT NULL UNIQUE,ativo TINYINT(1) DEFAULT 1) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS cores (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(60) NOT NULL UNIQUE,hex VARCHAR(7) NULL,ativo TINYINT(1) DEFAULT 1) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS tamanhos (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nome VARCHAR(30) NOT NULL UNIQUE,ordem INT DEFAULT 0,ativo TINYINT(1) DEFAULT 1) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
