SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL, usuario VARCHAR(60) NOT NULL UNIQUE, senha_hash VARCHAR(255) NOT NULL,
 nivel ENUM('admin','caixa','estoque') NOT NULL DEFAULT 'caixa', ativo TINYINT(1) NOT NULL DEFAULT 1,
 ultimo_acesso DATETIME NULL, criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 atualizado_em DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS configuracoes (
 chave VARCHAR(80) PRIMARY KEY, valor TEXT NULL, atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
